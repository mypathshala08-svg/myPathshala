"""8.3 Data skew and salting."""
import sys, json, urllib.request; sys.path.insert(0, "/root/lab/spark/jobs/m8")
from common import mk
from pyspark.sql import SparkSession, functions as F
spark = (SparkSession.builder.master("local[4]").config("spark.driver.memory", "3g")
         .config("spark.sql.adaptive.enabled", "false").config("spark.sql.shuffle.partitions", 8).getOrCreate())
sc = spark.sparkContext; stages, run = mk(spark)
def tasks(st):
    s = max(st, key=lambda s: s["numTasks"])
    t = json.load(urllib.request.urlopen(f"{sc.uiWebUrl}/api/v1/applications/{sc.applicationId}/stages/{s['stageId']}/{s['attemptId']}/taskList?length=500"))
    d = sorted(x["duration"] for x in t); r = sorted(x["taskMetrics"]["shuffleReadMetrics"]["recordsRead"] for x in t)
    print(f"   stage {s['stageId']}: {len(d)} tasks | duration ms min {d[0]} median {d[len(d)//2]} max {d[-1]} | records read min {r[0]} max {r[-1]}")
N = 6_000_000
# 60% of orders belong to one restaurant (a cloud kitchen chain)
o = spark.range(N).select(F.col("id").alias("order_id"),
      F.when(F.col("id") % 10 < 6, F.lit(1)).otherwise((F.col("id") % 4000) + 2).alias("rest_id"),
      (F.col("id") % 500).alias("amount"))
o.write.mode("overwrite").parquet("/root/lab/spark/data/m8/skew_orders"); o = spark.read.parquet("/root/lab/spark/data/m8/skew_orders")
print("top keys:"); o.groupBy("rest_id").count().orderBy(F.desc("count")).show(3)
sink = lambda df: (lambda: df.write.format("noop").mode("overwrite").save())
heavy = lambda df: df.withColumn("h", F.sha2(F.sha2(F.sha2(F.col("order_id").cast("string"), 256), 256), 256))
print("== 1) skewed window (per restaurant ranking)")
from pyspark.sql.window import Window
w = Window.partitionBy("rest_id").orderBy("amount")
q1 = heavy(o).withColumn("rk", F.row_number().over(w))
st = run("window by rest_id", sink(q1)); tasks(st)
print("== 2) groupBy is fine: partial aggregation before shuffle")
st = run("groupBy rest_id sum", sink(o.groupBy("rest_id").agg(F.sum("amount")))); tasks(st)
print("== 3) skewed join (hot key both sides, no broadcast)")
spark.conf.set("spark.sql.autoBroadcastJoinThreshold", -1)
menu = spark.range(400000).select((F.when(F.col("id") < 200, F.lit(1)).otherwise(F.col("id") % 4000 + 2)).alias("rest_id"), F.col("id").alias("item"))
j = o.join(menu, "rest_id").groupBy("rest_id").count()
print("join output rows for key 1 =", 3_600_000 * 200)
o_s = o.sample(0.05, 7)
j = o_s.join(menu, "rest_id")
st = run("skewed join (5% sample)", sink(j)); tasks(st)
print("== 4) salting the join: explode menu side, random salt on orders")
S = 16
os_ = o_s.withColumn("salt", (F.rand(1) * S).cast("int"))
ms = menu.withColumn("salt", F.explode(F.sequence(F.lit(0), F.lit(S - 1))))
js = os_.join(ms, ["rest_id", "salt"]).drop("salt")
print("same row count:", j.count() == js.count())
st = run(f"salted join, S={S}", sink(js)); tasks(st)
print("== 5) AQE skew join does it automatically")
spark.conf.set("spark.sql.adaptive.enabled", "true")
spark.conf.set("spark.sql.adaptive.skewJoin.skewedPartitionThresholdInBytes", "1m")
spark.conf.set("spark.sql.adaptive.skewJoin.skewedPartitionFactor", "2")
spark.conf.set("spark.sql.adaptive.advisoryPartitionSizeInBytes", "512k")
spark.conf.set("spark.sql.adaptive.coalescePartitions.enabled", "false")
ja = o_s.join(menu, "rest_id")
st = run("AQE skew join", sink(ja)); tasks(st)
ja.write.format("noop").mode("overwrite").save()
plan = ja._jdf.queryExecution().executedPlan().toString()
print("isSkewJoin=true in plan:", "isSkewJoin=true" in plan or "skew=true" in plan)
print("== 6) two-stage salted window alternative: split hot key")
spark.conf.set("spark.sql.adaptive.enabled", "false")
hot = o.filter("rest_id = 1"); cold = o.filter("rest_id <> 1")
q_hot = heavy(hot).repartitionByRange(8, "amount").sortWithinPartitions("amount")
st = run("hot key alone, range-partitioned", sink(q_hot)); tasks(st)
st = run("cold keys window", sink(heavy(cold).withColumn("rk", F.row_number().over(w)))); tasks(st)

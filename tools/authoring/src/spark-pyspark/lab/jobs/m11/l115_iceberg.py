"""11.5b Apache Iceberg (PySpark 4.1 + iceberg-spark-runtime-4.1 1.12.0, Hadoop catalog on local disk)."""
import os, shutil, warnings; warnings.filterwarnings("ignore")
from pyspark.sql import SparkSession, functions as F
W = "/root/lab/spark/data/m11/iceberg_wh"; shutil.rmtree(W, ignore_errors=True)
spark = (SparkSession.builder.master("local[2]").config("spark.ui.showConsoleProgress", "false")
         .config("spark.jars", "/root/lab/spark/jars/iceberg-spark-runtime-4.1_2.13-1.12.0.jar")
         .config("spark.sql.extensions", "org.apache.iceberg.spark.extensions.IcebergSparkSessionExtensions")
         .config("spark.sql.catalog.lake", "org.apache.iceberg.spark.SparkCatalog")
         .config("spark.sql.catalog.lake.type", "hadoop").config("spark.sql.catalog.lake.warehouse", W)
         .config("spark.sql.session.timeZone", "UTC").getOrCreate())
spark.sparkContext.setLogLevel("ERROR")
print("== 1) a table with hidden partitioning")
spark.sql("CREATE TABLE lake.db.orders (order_id BIGINT, city STRING, amount BIGINT, ts TIMESTAMP) USING iceberg PARTITIONED BY (days(ts))")
spark.sql("""INSERT INTO lake.db.orders VALUES (1,'Pune',450,TIMESTAMP'2026-11-01 10:00:00'),(2,'Mumbai',300,TIMESTAMP'2026-11-01 12:00:00'),
             (3,'Delhi',800,TIMESTAMP'2026-11-02 09:00:00')""")
print("data folders:", sorted(os.listdir(W + "/db/orders/data")))
print("metadata files:", sorted(f for f in os.listdir(W + "/db/orders/metadata") if not f.startswith("."))[:6])
print("== 2) filter on ts prunes partitions (no extra column needed)")
q = spark.sql("SELECT * FROM lake.db.orders WHERE ts >= TIMESTAMP'2026-11-02 00:00:00'")
print("rows:", q.count())
plan = q._jdf.queryExecution().executedPlan().toString()
print("scan filter pushed to Iceberg:", [l.strip()[:110] for l in plan.split("\n") if "BatchScan" in l][0].split(" [")[0], "...", "ts >=" in plan or "ts IS NOT NULL" in plan)
print("data files in table:", spark.sql("SELECT count(*) FROM lake.db.orders.files").first()[0], "| files in partition 2026-11-02:", spark.sql("SELECT count(*) FROM lake.db.orders.files WHERE partition.ts_day = DATE'2026-11-02'").first()[0])
print("== 3) row-level changes and snapshots")
spark.sql("UPDATE lake.db.orders SET amount = 500 WHERE order_id = 1")
spark.sql("DELETE FROM lake.db.orders WHERE order_id = 2")
spark.sql("SELECT snapshot_id, operation, summary['added-records'] AS added, summary['deleted-records'] AS deleted FROM lake.db.orders.snapshots ORDER BY committed_at").show(truncate=False)
first = spark.sql("SELECT snapshot_id FROM lake.db.orders.snapshots ORDER BY committed_at").first()[0]
print("time travel to first snapshot:", [(r.order_id, r.amount) for r in spark.sql(f"SELECT * FROM lake.db.orders VERSION AS OF {first} ORDER BY order_id").collect()])
print("now:", [(r.order_id, r.amount) for r in spark.sql("SELECT * FROM lake.db.orders ORDER BY order_id").collect()])
print("== 4) schema and partition evolution without rewriting data")
spark.sql("ALTER TABLE lake.db.orders ADD COLUMN payment STRING")
spark.sql("ALTER TABLE lake.db.orders RENAME COLUMN amount TO amount_rs")
spark.sql("ALTER TABLE lake.db.orders ADD PARTITION FIELD city")
spark.sql("INSERT INTO lake.db.orders VALUES (4,'Thane',120,TIMESTAMP'2026-11-03 08:00:00','UPI')")
spark.sql("SELECT * FROM lake.db.orders ORDER BY order_id").show()
print("partition specs:", [r.spec_id for r in spark.sql("SELECT DISTINCT spec_id FROM lake.db.orders.files").collect()])
print("new file path:", [os.path.relpath(os.path.join(d, x), W) for d, _, fs in os.walk(W + "/db/orders/data/ts_day=2026-11-03") for x in fs if x.endswith(".parquet")])

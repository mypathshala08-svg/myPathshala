#!/usr/bin/env node
/**
 * MyPhatshala: site builder
 * ------------------------------------------------------------
 * A website cannot list folders, so this script scans them for it.
 * Run it after adding or changing anything in courses/:
 *     node tools/build-manifest.js      (or double-click build.bat)
 * On GitHub it runs automatically on every push.
 *
 * It reads:
 *   courses/_tracks.json                 tracks (categories) and their order
 *   courses/_paths.json                  career learning paths
 *   courses/<course>/course.json         one syllabus per course
 *   courses/<course>/<module>/<lesson>/index.html
 *        exists  → lesson is LIVE    (Start button, added to sitemap)
 *        missing → lesson is "Coming soon"
 *
 * It writes:
 *   data/catalog.js        small summary for the home page (tracks, courses, paths)
 *   data/search-index.js   every lesson title, loaded only when someone searches
 *   data/manifest.json     everything, for reference and future tools
 *   courses/<course>/index.html   a generated syllabus page per course (SEO-friendly)
 *   sitemap.xml            every course page and live lesson, for Google
 *
 * Plain Node.js 16+. No npm packages.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const COURSES = path.join(ROOT, "courses");
const DATA = path.join(ROOT, "data");
const TEMPLATE = path.join(__dirname, "templates", "course.html");
const GENERATED_MARK = "<!-- GENERATED by tools/build-manifest.js";

const warn = [];
const readJSON = p => JSON.parse(fs.readFileSync(p, "utf8"));
const esc = s => String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

function siteUrl() {
  try {
    const m = fs.readFileSync(path.join(ROOT, "assets/js/config.js"), "utf8").match(/siteUrl\s*:\s*["']([^"']+)["']/);
    return m ? m[1].replace(/\/$/, "") : "https://example.com";
  } catch { return "https://example.com"; }
}
const meta = (html, name) => {
  const m = html.match(new RegExp(`<meta\\s+name=["']${name}["']\\s+content=["']([^"']*)["']`, "i"));
  return m ? m[1].trim() : null;
};
const titleOf = html => {
  const m = html.match(/<title>([^<]*)<\/title>/i);
  return m ? m[1].replace(/\s*[|·–-]\s*MyPhatshala\s*$/i, "").trim()
    .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#x27;|&#39;/g, "'").replace(/&amp;/g, "&") : null;
};

// ------------------------------------------------------------------ load
const tracks = readJSON(path.join(COURSES, "_tracks.json")).tracks;
const pathsCfg = fs.existsSync(path.join(COURSES, "_paths.json")) ? readJSON(path.join(COURSES, "_paths.json")).paths : [];
const trackById = Object.fromEntries(tracks.map(t => [t.id, t]));

const courses = [];
for (const dir of fs.readdirSync(COURSES, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const cfgPath = path.join(COURSES, dir.name, "course.json");
  if (!fs.existsSync(cfgPath)) { warn.push(`courses/${dir.name}: no course.json, skipped`); continue; }
  const c = readJSON(cfgPath);
  if (c.id !== dir.name) warn.push(`courses/${dir.name}: "id" is "${c.id}" but folder is "${dir.name}" (folder name is used)`);
  c.id = dir.name;
  if (!trackById[c.category]) { warn.push(`${c.id}: unknown category "${c.category}", put in "more"`); c.category = "more"; }

  let total = 0, live = 0;
  c.modules = (c.modules || []).map((m, mi) => ({
    ...m,
    number: mi + 1,
    lessons: (m.lessons || []).map((l, li) => {
      total++;
      const rel = `${m.slug}/${l.slug}/`;
      const file = path.join(COURSES, c.id, m.slug, l.slug, "index.html");
      const out = { slug: l.slug, number: `${mi + 1}.${li + 1}`, title: l.title, rel, status: "soon" };
      if (fs.existsSync(file)) {
        const html = fs.readFileSync(file, "utf8");
        Object.assign(out, {
          status: "live",
          title: titleOf(html) || l.title,
          description: meta(html, "description") || "",
          minutes: Number(meta(html, "mp:minutes")) || null,
        });
        live++;
      }
      return out;
    }),
  }));
  c.stats = { modules: c.modules.length, lessons: total, live };
  c.url = `courses/${c.id}/`;
  courses.push(c);
}
courses.sort((a, b) => (a.order ?? 99) - (b.order ?? 99) || a.title.localeCompare(b.title));
const courseById = Object.fromEntries(courses.map(c => [c.id, c]));

// ------------------------------------------------------------------ catalog (home page)
const catalogTracks = tracks.map(t => ({
  ...t,
  courses: courses.filter(c => c.category === t.id).map(c => ({
    id: c.id, title: c.title, tagline: c.tagline, level: c.level, url: c.url, stats: c.stats,
  })),
})).filter(t => t.courses.length);

const catalogPaths = pathsCfg.map(p => ({
  ...p,
  courses: p.courses.filter(id => courseById[id] || (warn.push(`path "${p.id}": unknown course "${id}"`), false))
    .map(id => ({ id, title: courseById[id].title, url: courseById[id].url })),
}));

const totals = courses.reduce((a, c) => {
  a.courses++; a.modules += c.stats.modules; a.lessons += c.stats.lessons; a.live += c.stats.live; return a;
}, { tracks: catalogTracks.length, courses: 0, modules: 0, lessons: 0, live: 0 });

fs.mkdirSync(DATA, { recursive: true });
const stamp = new Date().toISOString();
fs.writeFileSync(path.join(DATA, "catalog.js"),
  "/* AUTO-GENERATED by tools/build-manifest.js. Do not edit by hand. */\n" +
  "window.MP_CATALOG = " + JSON.stringify({ generatedAt: stamp, totals, tracks: catalogTracks, paths: catalogPaths }) + ";\n");

// ------------------------------------------------------------------ search index (lazy)
const search = [];
for (const c of courses) {
  search.push([c.title, trackById[c.category].title, c.url, "course"]);
  for (const m of c.modules) for (const l of m.lessons) {
    search.push([l.title, c.title, c.url + (l.status === "live" ? l.rel : "#m" + m.number), l.status]);
  }
}
fs.writeFileSync(path.join(DATA, "search-index.js"),
  "/* AUTO-GENERATED. [title, course, url, status] */\nwindow.MP_SEARCH = " + JSON.stringify(search) + ";\n");

// per-course outline, used by lesson pages for the sidebar and Previous/Next links
fs.mkdirSync(path.join(DATA, "courses"), { recursive: true });
for (const c of courses) {
  const outline = {
    id: c.id, title: c.title, track: trackById[c.category].title, color: trackById[c.category].color,
    modules: c.modules.map(m => ({ n: m.number, slug: m.slug, title: m.title,
      lessons: m.lessons.map(l => ({ n: l.number, slug: l.slug, title: l.title, live: l.status === "live", min: l.minutes || null })) })),
  };
  fs.writeFileSync(path.join(DATA, "courses", `${c.id}.js`),
    "/* AUTO-GENERATED by tools/build-manifest.js */\nwindow.MP_COURSE = " + JSON.stringify(outline) + ";\n");
}

fs.writeFileSync(path.join(DATA, "manifest.json"), JSON.stringify({ generatedAt: stamp, totals, tracks, courses }, null, 2));
const oldManifestJs = path.join(DATA, "manifest.js");
if (fs.existsSync(oldManifestJs)) fs.unlinkSync(oldManifestJs); // replaced by catalog.js

// ------------------------------------------------------------------ course pages
const template = fs.readFileSync(TEMPLATE, "utf8");
const base = siteUrl();

// A prerequisite that points to a lesson of this course which is not live yet links to its module in the syllabus instead (no 404).
function prereqHref(c, href) {
  for (const m of c.modules) for (const l of m.lessons) if (l.rel === href || l.rel === href + "/") return l.status === "live" ? href : "#m" + m.number;
  return href;
}
for (const c of courses) {
  const t = trackById[c.category];
  const out = path.join(COURSES, c.id, "index.html");
  if (fs.existsSync(out) && !fs.readFileSync(out, "utf8").includes(GENERATED_MARK)) {
    warn.push(`${c.id}: courses/${c.id}/index.html was hand-written, not overwritten`);
    continue;
  }
  const pct = c.stats.lessons ? Math.round(c.stats.live / c.stats.lessons * 100) : 0;
  const syllabus = c.modules.map((m, i) => `
      <details class="module" id="m${m.number}"${i === 0 ? " open" : ""}>
        <summary>
          <span class="module__num">${String(m.number).padStart(2, "0")}</span>
          <span class="module__text"><strong>${esc(m.title)}</strong><em>${esc(m.summary)}</em></span>
          <span class="module__count">${m.lessons.length} lessons</span>
          <svg class="module__chev" viewBox="0 0 24 24" aria-hidden="true"><path d="M6 9l6 6 6-6"/></svg>
        </summary>
        <ol class="lessons">${m.lessons.map(l => l.status === "live"
          ? `
          <li class="lesson is-live" data-search="${esc(l.title.toLowerCase())}"><a href="${esc(l.rel)}"><span class="lesson__num">${l.number}</span><span class="lesson__title">${esc(l.title)}</span>${l.minutes ? `<span class="lesson__min">${l.minutes} min</span>` : ""}<span class="badge badge--live">Start</span></a></li>`
          : `
          <li class="lesson is-soon" data-search="${esc(l.title.toLowerCase())}"><span class="lesson__num">${l.number}</span><span class="lesson__title">${esc(l.title)}</span><span class="badge">Coming soon</span></li>`).join("")}
        </ol>
      </details>`).join("");

  const related = courses.filter(o => o.category === c.category && o.id !== c.id)
    .map(o => `<a href="../${o.id}/">${esc(o.title)}<span>${o.stats.lessons} lessons</span></a>`).join("");
  const inPaths = catalogPaths.filter(p => p.courses.some(pc => pc.id === c.id))
    .map(p => `<a href="../../#paths">${esc(p.title)} path</a>`).join("");
  const firstLive = c.modules.flatMap(m => m.lessons).find(l => l.status === "live");
  const jsonld = JSON.stringify({
    "@context": "https://schema.org", "@type": "Course", name: c.title, description: c.tagline,
    provider: { "@type": "Organization", name: "MyPhatshala", sameAs: base + "/" },
    isAccessibleForFree: true, educationalLevel: c.level, url: `${base}/${c.url}`,
  });

  const html = template
    .replaceAll("{{GENERATED}}", `${GENERATED_MARK} from courses/${c.id}/course.json. Edit that file, not this one. -->`)
    .replaceAll("{{TITLE}}", esc(c.title))
    .replaceAll("{{TAGLINE}}", esc(c.tagline))
    .replaceAll("{{LEVEL}}", esc(c.level))
    .replaceAll("{{CANONICAL}}", `${base}/${c.url}`)
    .replaceAll("{{TRACK}}", esc(t.title))
    .replaceAll("{{TRACK_ID}}", esc(t.id))
    .replaceAll("{{COLOR}}", esc(t.color))
    .replaceAll("{{MODULES}}", c.stats.modules)
    .replaceAll("{{LESSONS}}", c.stats.lessons)
    .replaceAll("{{LIVE}}", c.stats.live)
    .replaceAll("{{PCT}}", Math.max(pct, 2))
    .replaceAll("{{START_URL}}", firstLive ? esc(firstLive.rel) : "#syllabus")
    .replaceAll("{{START_LABEL}}", firstLive ? "Start the course" : "View syllabus")
    .replaceAll("{{SYLLABUS}}", syllabus)
    .replaceAll("{{RELATED}}", related || "<p class=\"muted\">More courses coming to this track.</p>")
    .replaceAll("{{PATHS}}", inPaths ? `<h4>Part of these career paths</h4>${inPaths}` : "")
    .replaceAll("{{EXTRAS}}", ((c.prerequisites || []).length ? `<div class="aside-card aside-card--notes"><h4>Before you start</h4><p class="muted">Helpful to know first:</p>${c.prerequisites.map(x => `<a href="${esc(prereqHref(c, x.href))}">${esc(x.title)}<span>${esc(x.note || "")}</span></a>`).join("")}</div>` : "") + ((c.extras || []).length ? `<div class="aside-card aside-card--notes"><h4>Course tools</h4>${c.extras.map(x => `<a href="${esc(x.href)}">${esc(x.title)}<span>${esc(x.note || "")}</span></a>`).join("")}</div>` : ""))
    .replaceAll("{{JSONLD}}", jsonld);
  fs.writeFileSync(out, html);
}

// ------------------------------------------------------------------ sitemap
const today = stamp.slice(0, 10);
const urls = [`${base}/`, ...courses.map(c => `${base}/${c.url}`)];
for (const c of courses) for (const m of c.modules) for (const l of m.lessons)
  if (l.status === "live") urls.push(`${base}/${c.url}${l.rel}`);
for (const c of courses) for (const x of c.extras || []) if (!/^(https?:|\/|\.\.)/.test(x.href)) urls.push(`${base}/${c.url}${x.href}`);
fs.writeFileSync(path.join(ROOT, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  urls.map(u => `  <url><loc>${u}</loc><lastmod>${today}</lastmod></url>`).join("\n") + `\n</urlset>\n`);

// ------------------------------------------------------------------ report
for (const t of catalogTracks) {
  const n = t.courses.reduce((a, c) => a + c.stats.lessons, 0);
  const l = t.courses.reduce((a, c) => a + c.stats.live, 0);
  console.log(`✔ ${t.title.padEnd(36)} ${String(t.courses.length).padStart(2)} courses ${String(n).padStart(4)} lessons (${l} live)`);
}
console.log(`\n✔ TOTAL: ${totals.tracks} tracks, ${totals.courses} courses, ${totals.modules} modules, ${totals.lessons} lessons, ${totals.live} live`);
console.log(`✔ wrote data/catalog.js, data/search-index.js, data/manifest.json, ${courses.length} course pages, sitemap.xml (${urls.length} URLs)`);
if (warn.length) { console.log("\n⚠ Warnings:"); warn.forEach(w => console.log("  - " + w)); }
